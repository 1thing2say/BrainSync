"""FastAPI server: serves the partner page (ui/), its websocket /ws/ui, and the decoder websocket
/ws/decoder (INTERFACE.md).

One active partner page and one active decoder at a time; a new connection replaces the old one.
All state lives in the orchestrator, which runs in the event loop and is ticked every TICK_S.
Pages of reply options come from the LLM backends (app/menus.py: a local llama-server, then
Claude) after each partner line and for "More options". Cartesia clips for the current page are
pre-generated by app/tts.py and served at /audio/{id}. ``main`` reads ANTHROPIC_API_KEY,
BRAINSYNC_LLAMA_API_KEY (each backend's ``api_key_env``) and CARTESIA_API_KEY from the environment
or the gitignored .env.

    python -m app.server                    # real decoder connects to /ws/decoder
    python -m app.server --fake-decoder     # also start tools/fake_decoder.py --random
    python -m app.server --keyboard         # keys 1-4 on the partner page select
    python -m app.server --tunnel           # also a public https link for the partner's phone
"""

