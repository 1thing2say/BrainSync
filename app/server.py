"""FastAPI server: serves the partner page (ui/), its websocket /ws/ui, and the decoder websocket
/ws/decoder (INTERFACE.md).

One active partner page and one active decoder at a time; a new connection replaces the old one.
All state lives in the orchestrator, which runs in the event loop and is ticked every TICK_S.
Pages of reply options come from Claude (app/menus.py) after each partner line and for "More
options". Cartesia clips for the current page are pre-generated by app/tts.py and served at
/audio/{id}. ``main`` reads ANTHROPIC_API_KEY and CARTESIA_API_KEY from the environment or the
gitignored .env.

    python -m app.server                    # real decoder connects to /ws/decoder
    python -m app.server --fake-decoder     # also start tools/fake_decoder.py --random
    python -m app.server --bridge cerelog   # also start brainsync.voice_bridge (headset + display)
    python -m app.server --bridge fake --bridge-headless   # the bridge on fake EEG, no window
    python -m app.server --keyboard         # keys 1-4 on the partner page select
    python -m app.server --tunnel           # also a public https link for the partner's phone
    python -m app.server --config config/fvep_page.yaml   # the 4-target f-VEP fallback

The default config is c-VEP (three targets: 2 options + NEXT, a training step instead of the
baseline, confidence bars; docs/CVEP-STANDARD.md); --bridge and --fake-decoder follow the
config's paradigm.
"""

