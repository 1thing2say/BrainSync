#!/usr/bin/env python3
"""render-grub.py - BrainSyncOS boot menu from NVIDIA's Jetson ISO grub.cfg.

Usage: render-grub.py VENDOR_GRUB_CFG OUT --version V --build-id ID
                      --default nvme|microsd|usb --timeout SECONDS
                      [--base-iso NAME]

Every kernel command line is copied verbatim from the vendor entries (they
carry `autoinstall`, force-bootdisk= and NVIDIA's Tegra boot parameters); only
titles, order, the default entry and the timeout change. Fails if the vendor
file no longer has exactly the entries this script knows about, so a new
base ISO cannot silently lose an install target.
"""

import argparse
import re
import sys

# Vendor menuentry title -> our key. All must be present exactly once.
VENDOR_ENTRIES = {
    "Install on NVMe": "nvme",
    "Install on USB": "usb",
    "Install on eMMC (for AGX Orin)": "emmc",
    "Install on microSD (for AGX Orin, Orin Nano/NX)": "microsd",
    "Boot Into Rescue Shell": "rescue",
    "Check Disc for Defects": "check",
}
INSTALL_TITLES = {
    "nvme": "on NVMe SSD",
    "microsd": "on microSD card",
    "usb": "on USB drive",
}
ENTRY_RE = re.compile(
    r'^\s*menuentry\s+"(?P<title>[^"]+)"\s*\{\s*\n'
    r'\s*(?P<linux>linux\s+[^\n]+)\n'
    r'\s*(?P<initrd>initrd\s+[^\n]+)\n'
    r'\s*\}',
    re.M,
)


def fail(msg):
    sys.exit("render-grub.py: " + msg)


def parse_vendor(text):
    sub = re.search(r'^submenu\s+"[^"]*"\s*\{\n(?P<body>.*?)^\}\n', text, re.M | re.S)
    if not sub:
        fail("no submenu block in vendor grub.cfg")
    entries = {}
    for m in ENTRY_RE.finditer(sub.group("body")):
        key = VENDOR_ENTRIES.get(m.group("title"))
        if key is None:
            fail("unknown vendor entry %r (update VENDOR_ENTRIES)" % m.group("title"))
        if key in entries:
            fail("duplicate vendor entry %r" % m.group("title"))
        entries[key] = (m.group("linux"), m.group("initrd"))
    missing = sorted(set(VENDOR_ENTRIES.values()) - set(entries))
    if missing:
        fail("vendor grub.cfg lacks entries: %s" % ", ".join(missing))
    for key in ("nvme", "usb", "emmc", "microsd"):
        if " autoinstall " not in entries[key][0] + " ":
            fail("vendor %s entry has no autoinstall flag" % key)
    # Everything after the submenu (Boot from next volume, UEFI settings) is kept as-is.
    trailer = text[sub.end():].strip("\n")
    return entries, trailer


def entry(title, linux_initrd, indent=""):
    linux, initrd = linux_initrd
    return "\n".join([
        '%smenuentry "%s" {' % (indent, title),
        "%s    %s" % (indent, linux),
        "%s    %s" % (indent, initrd),
        "%s}" % indent,
    ])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vendor")
    ap.add_argument("out")
    ap.add_argument("--version", required=True)
    ap.add_argument("--build-id", required=True)
    ap.add_argument("--default", required=True, choices=sorted(INSTALL_TITLES))
    ap.add_argument("--timeout", required=True, type=int)
    ap.add_argument("--base-iso", default="the NVIDIA Jetson ISO")
    a = ap.parse_args()
    if a.timeout < -1:
        fail("--timeout must be -1 or >= 0")

    with open(a.vendor) as f:
        entries, trailer = parse_vendor(f.read())

    order = [a.default] + [k for k in ("nvme", "microsd", "usb") if k != a.default]
    name = "BrainSyncOS %s" % a.version
    parts = [
        "# %s (build %s) boot menu." % (name, a.build_id),
        "# Generated by brainsyncos/scripts/render-grub.py from the grub.cfg of",
        "# %s; kernel command lines are NVIDIA's, unchanged." % a.base_iso,
        "set menu_color_normal=white/black",
        "set menu_color_highlight=black/light-gray",
        "",
        "insmod gzio",
        "",
        "set default=0",
        "set timeout=%d" % a.timeout,
        "",
    ]
    for key in order:
        parts += [entry("Install %s %s (Jetson Orin Nano)" % (name, INSTALL_TITLES[key]), entries[key]), ""]
    parts += [
        'submenu "Advanced options" {',
        entry("Install %s on eMMC (AGX Orin)" % name, entries["emmc"], "    "),
        "",
        entry("Boot Into Rescue Shell", entries["rescue"], "    "),
        "",
        entry("Check Disc for Defects", entries["check"], "    "),
        "}",
        "",
        trailer,
        "",
    ]
    with open(a.out, "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
