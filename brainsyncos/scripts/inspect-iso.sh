#!/usr/bin/env bash
# inspect-iso.sh - write build/reports/base-iso-inventory.md (builder only).
#
# Usage: scripts/builder.sh run scripts/inspect-iso.sh [--no-sigcheck]
#
# Needs build/iso-root/ (scripts/extract-iso.sh). Reports: identity, boot
# structure (El Torito, GPT, ESP contents), grub boot entries, casper layers
# (size, compression, date, signature status, which ones the live installer
# mounts), kernel/L4T versions, where the embedded autoinstall config lives
# and what it contains, nvidia-l4t packages in the pool, and signing/integrity
# notes (squashfs .gpg, apt InRelease, md5sum.txt). --no-sigcheck skips the
# slow parts (gpgv over ~1.5 GB of squashfs, md5sum -c over the whole tree).
# A full run (without --no-sigcheck) also copies the report to the tracked
# docs/base-iso-inventory.md; it holds container paths only (/in, /work).

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)/lib.sh"
load_config

sigcheck=1
while [ "$#" -gt 0 ]; do
    case "$1" in
        --no-sigcheck) sigcheck=0; shift ;;
        -h|--help) usage_from_header; exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
done
require_container
require_cmd xorriso unsquashfs unmkinitramfs gpgv mdir sfdisk python3 md5sum
[ -d "$ISO_ROOT" ] && [ -f "$META_DIR/extract.stamp" ] || die "no extracted tree; run scripts/extract-iso.sh first"

iso="$(resolve_base_iso)"
R="$ISO_ROOT"
C="$R/casper"
AI_SQ="$C/$AUTOINSTALL_LAYER"
mkdir -p "$REPORTS_DIR" "$TMP_DIR"
work="$(mktemp -d "$TMP_DIR/inspect.XXXXXX")"
trap 'force_rm_tree "$work"' EXIT
report="$REPORTS_DIR/base-iso-inventory.md"
out="$work/report.md"

md() { printf '%s\n' "$@" >> "$out"; }
code() { md '```'"${1:-}"; cat >> "$out"; md '```' ''; }
sq_field() { unsquashfs -s "$1" 2>/dev/null | sed -n "s/^$2 //p" | head -1; }

log "collecting identity"
. "$META_DIR/esp.env"
md "# Base ISO inventory: $BASE_ISO_NAME" ''
md "Generated by \`scripts/inspect-iso.sh\` from \`build/iso-root\` (extract stamp: \`$(cat "$META_DIR/extract.stamp")\`). The output is deterministic for a given base ISO; \`docs/base-iso-inventory.md\` is the tracked copy." ''
md '## Identity' '' '| field | value |' '|---|---|'
md "| file | \`$BASE_ISO_NAME\` (user-supplied, never committed) |"
md "| size | $(file_size "$iso") bytes |"
md "| sha256 | \`$BASE_ISO_SHA256\` (verified by verify-base-iso.sh) |"
md "| volume id | \`$BASE_ISO_VOLID\` |"
md "| .disk/info | $(cat "$R/.disk/info") |"
xorriso -indev "$iso" -pvd_info 2>/dev/null > "$work/pvd"
md "| PVD preparer | $(sed -n 's/^Preparer Id *: //p' "$work/pvd") |"
md "| PVD creation / modification | $(sed -n 's/^Creation Time: //p' "$work/pvd") / $(sed -n 's/^Modif. Time *: //p' "$work/pvd") |"
md "| L4T / JetPack | $L4T_RELEASE / ${JETPACK_RELEASE:-?} |"
md "| target kernel (nvidia-l4t-kernel) | \`$TEGRA_KERNEL\` |"

log "unpacking initrd"
mkdir -p "$work/initrd"
unmkinitramfs "$C/initrd" "$work/initrd" >/dev/null 2>&1 || warn "unmkinitramfs reported errors"
live_kernel=""
if [ -d "$work/initrd/main/usr/lib/modules" ]; then
    live_kernel="$(ls "$work/initrd/main/usr/lib/modules" | head -1)"
else
    warn "no usr/lib/modules in the unpacked initrd"
fi
layer_conf="$work/initrd/main/conf/conf.d/default-layer.conf"
layerfs=""
if [ -f "$layer_conf" ]; then
    layerfs="$(sed -n 's/^LAYERFS_PATH=//p' "$layer_conf" | tr -d '"')"
fi
if [ -z "$layerfs" ]; then
    warn "no LAYERFS_PATH in initrd conf/conf.d/default-layer.conf; using CASPER_LAYERFS_PATH from config"
    layerfs="$CASPER_LAYERFS_PATH"
fi
md "| live installer kernel | \`${live_kernel:-unknown}\` (initrd modules; config says \`$LIVE_KERNEL\`) |" ''

md '## Boot structure' ''
md 'UEFI arm64 only. Protective MBR + GPT; the El Torito UEFI image is the appended EFI System partition, not a file in the tree.' ''
code < "$META_DIR/el-torito.plain.txt"
md 'Replay options (`-report_el_torito as_mkisofs`):' ''
code < "$META_DIR/el-torito.as_mkisofs.txt"
md 'Partition table (`sfdisk -d`):' ''
grep -v '^device:' "$META_DIR/partitions.sfdisk.txt" | sed "s#^$iso#ISO#" | code
md "ESP: sectors $ESP_START_SECTOR+$ESP_SIZE_SECTORS, sha256 \`$(cat "$META_DIR/esp.sha256")\`. Contents (mtools):" ''
esp_img="$iso@@$((ESP_START_SECTOR * 512))"
{ MTOOLS_SKIP_CHECK=1 mdir -i "$esp_img" ::/EFI 2>&1; MTOOLS_SKIP_CHECK=1 mdir -i "$esp_img" ::/EFI/BOOT 2>&1; } | code
md 'The ESP `EFI/BOOT/bootaa64.efi` is NVIDIA'"'"'s L4TLauncher (firmware/capsule check, then shim -> grub); `TEGRA_BL_*.Cap` are QSPI capsules. Repack copies the ESP verbatim; never rebuild it.' ''

log "parsing grub.cfg"
md '## Boot entries (`boot/grub/grub.cfg`)' ''
md "default=\`$(sed -n 's/^set default=//p' "$R/boot/grub/grub.cfg")\`, timeout=\`$(sed -n 's/^set timeout=//p' "$R/boot/grub/grub.cfg")\` (-1 = wait forever)." ''
md '| entry | force-bootdisk | notable kernel args |' '|---|---|---|'
awk '
    /menuentry/ { t = $0; sub(/^[^"'"'"']*["'"'"']/, "", t); sub(/["'"'"'].*$/, "", t) }
    /^[ \t]*linux / {
        fb = "-"; flags = ""
        for (i = 3; i <= NF; i++) {
            if ($i ~ /^force-bootdisk=/) { fb = substr($i, 16) }
            else if ($i ~ /^(autoinstall|cloud-init=|subiquity\.|boot-live-env|md5checkdisc|systemd\.unit=|fsck\.mode=|layerfs-path=)/) { flags = flags " `" $i "`" }
        }
        printf "| %s | %s |%s |\n", t, fb, flags
    }' "$R/boot/grub/grub.cfg" >> "$out"
md '' 'Common args on every entry: `mminit_loglevel=4 clk_ignore_unused pd_ignore_unused firmware_class.path=/etc/firmware fbcon=map:0 nospectre_bhb efi=runtime rd.driver.blacklist=nouveau nouveau.modeset=0`.' ''

log "inspecting casper layers"
chain=""
l="$layerfs"
while [ -n "$l" ]; do
    chain="$l $chain"
    case "${l%.squashfs}" in *.*) l="${l%.squashfs}"; l="${l%.*}.squashfs" ;; *) l="" ;; esac
done
key_cd="$work/ubuntu-cdimage.gpg"
unsquashfs -cat "$C/ubuntu-server-minimal.squashfs" etc/apt/trusted.gpg.d/ubuntu-keyring-2012-cdimage.gpg > "$key_cd" 2>/dev/null || true
md '## Casper layers' ''
md "Live installer layer chain (initrd \`conf/conf.d/default-layer.conf\`: \`LAYERFS_PATH=$layerfs\`; casper strips one dotted suffix at a time; \`layerfs-path=\` on the cmdline overrides):" ''
for l in $chain; do md "1. \`$l\`"; done
md '' '| layer | bytes | comp | created | inodes | live chain | .gpg |' '|---|---|---|---|---|---|---|'
for sq in "$C"/*.squashfs; do
    b="$(basename "$sq")"
    case " $chain " in *" $b "*) used=yes ;; *) used=no ;; esac
    if [ ! -f "$sq.gpg" ]; then
        sig="none"
    elif [ "$sigcheck" = 0 ]; then
        sig="present (not checked)"
    elif gpgv --keyring "$key_cd" "$sq.gpg" "$sq" >/dev/null 2>&1; then
        sig="Good"
    else
        sig="**BAD**"
    fi
    md "| \`$b\` | $(file_size "$sq") | $(sq_field "$sq" Compression) | $(sq_field "$sq" 'Creation or last append time') | $(sq_field "$sq" 'Number of inodes') | $used | $sig |"
done
md '' 'Install sources (`casper/install-sources.yaml`; the *target* rootfs is built from these OS layers only, the installer/kernel/nvidia layers never reach the installed system):' ''
code yaml < "$C/install-sources.yaml"

log "kernel and L4T packages"
md '## Kernel and L4T packages (kernel layer manifest)' ''
md "\`$KERNEL_LAYER_MANIFEST\` (installer layer; \`+\` = added by this layer):" ''
grep -E '^\+?(nvidia-l4t|linux-)' "$R/$KERNEL_LAYER_MANIFEST" | code

log "embedded autoinstall"
md '## Embedded autoinstall config' ''
md "**Location:** \`/autoinstall.yaml\` at the root of the live filesystem, provided by the NVIDIA overlay layer \`casper/$AUTOINSTALL_LAYER\` (not at the ISO root, not in the initrd). Subiquity's \`select_autoinstall()\` order: \`--autoinstall\` arg, kernel \`subiquity.autoinstallpath=\`, \`/autoinstall.yaml\`, \`/run/subiquity/cloud.autoinstall.yaml\`, \`/cdrom/autoinstall.yaml\`; so this file beats an ISO-root \`/autoinstall.yaml\`." ''
md '`/autoinstall.yaml`:' ''
unsquashfs -cat "$AI_SQ" autoinstall.yaml | code yaml
md 'It runs `/ai/preseed.sh jetsoniso`, which detects the board (DT model), repartitions the boot disk from `/opt/nvidia/ptable.<family>.<type>.dynamic` (unless `preserve-part`), fills the `CHANGE_*` placeholders of `/ai/jetsoniso_<family>-ai.yaml` with `sed -i` and copies it over `/autoinstall.yaml`; subiquity re-reads it after early-commands.' ''
md 'Files in the layer:' ''
unsquashfs -lls "$AI_SQ" autoinstall.yaml ai opt/nvidia 2>/dev/null \
    | awk '$6 ~ /^squashfs-root\// { sub(/^squashfs-root/, "", $6); printf "%s %8s", $1, $3; for (i = 6; i <= NF; i++) printf " %s", $i; print "" }' | code
for f in jetsoniso_orin-ai.yaml jetsoniso_thor-ai.yaml; do
    unsquashfs -cat "$AI_SQ" "ai/$f" > "$work/$f" 2>/dev/null || continue
done
unsquashfs -cat "$AI_SQ" ai/jetsoniso-pkgs > "$work/pkgs" 2>/dev/null || true
unsquashfs -cat "$AI_SQ" ai/jetsoniso-removed-pkgs > "$work/rmpkgs" 2>/dev/null || true
md '| per-platform AI file | lines | top-level keys | late-commands | placeholders |' '|---|---|---|---|---|'
python3 -I - "$work/jetsoniso_orin-ai.yaml" "$work/jetsoniso_thor-ai.yaml" >> "$out" <<'PY'
import re, sys, yaml
for path in sys.argv[1:]:
    try:
        text = open(path).read()
    except OSError:
        continue
    name = path.rsplit("/", 1)[-1]
    ph = sorted(set(re.findall(r"#?CHANGE_[A-Z0-9_]+|[A-Z_]*_DYNAMIC_APP_SIZE", text)))
    try:
        doc = yaml.safe_load(text)
        ai = doc.get("autoinstall", doc) if isinstance(doc, dict) else {}
        keys = ", ".join(sorted(ai)) if isinstance(ai, dict) else "?"
        late = len(ai.get("late-commands") or []) if isinstance(ai, dict) else "?"
    except yaml.YAMLError as e:
        keys, late = "unparsed (%s)" % e.__class__.__name__, "?"
    print("| `/ai/%s` | %d | %s | %s | %s |" % (name, text.count("\n"), keys, late, " ".join("`%s`" % p for p in ph)))
PY
# Count package entries, not blank or comment lines (grep -c exits 1 on 0 matches).
count_pkgs() { grep -cvE '^[[:space:]]*(#|$)' "$1" 2>/dev/null || true; }
n_pkgs="$(count_pkgs "$work/pkgs")"
n_rmpkgs="$(count_pkgs "$work/rmpkgs")"
md '' "Package list \`/ai/jetsoniso-pkgs\`: ${n_pkgs:-0} packages (installed --no-install-recommends from the ISO pool by a late-command); \`/ai/jetsoniso-removed-pkgs\`: ${n_rmpkgs:-0} packages purged afterwards (comment and blank lines not counted)." ''

log "pool packages"
md '## ISO apt repository (pool)' ''
python3 -I - "$R/dists/$UBUNTU_CODENAME" >> "$out" <<'PY'
import glob, os, sys
base = sys.argv[1]
pkgs = {}
for p in glob.glob(os.path.join(base, "*", "binary-arm64", "Packages")):
    comp = p.split(os.sep)[-3]
    for stanza in open(p, encoding="utf-8", errors="replace").read().split("\n\n"):
        f = {}
        for line in stanza.splitlines():
            if line and not line[0].isspace() and ":" in line:
                k, v = line.split(":", 1)
                f[k] = v.strip()
        if "Package" in f:
            pkgs[f["Package"]] = (f.get("Version", "?"), comp)
print("%d packages indexed (%s).\n" % (len(pkgs), ", ".join(sorted({c for _, c in pkgs.values()}))))
print("nvidia-l4t packages:\n")
print("| package | version |\n|---|---|")
for n in sorted(pkgs):
    if n.startswith("nvidia-l4t"):
        print("| `%s` | `%s` |" % (n, pkgs[n][0]))
want = ["python3-numpy", "python3-scipy", "python3-serial", "python3-pip", "python3-venv",
        "python3-pyqt5", "python3-psychopy", "liblsl", "liblsl-dev", "cage", "weston",
        "cuda-toolkit-13-2", "tensorrt", "docker.io", "nvidia-container-toolkit", "ubuntu-desktop", "gdm3"]
print("\nPackages later phases care about (present in pool?):\n")
print("| package | in pool |\n|---|---|")
for n in want:
    print("| `%s` | %s |" % (n, ("yes " + pkgs[n][0]) if n in pkgs else "**no**"))
PY
md ''

log "signing and integrity"
md '## Signing and integrity' ''
key_dgx="$work/dgx.gpg"
unsquashfs -cat "$C/ubuntu-server-minimal.ubuntu-server.squashfs" etc/apt/trusted.gpg.d/dgx_debian_prod.gpg > "$key_dgx" 2>/dev/null || true
inrel_key="$(gpgv --keyring /dev/null "$R/dists/$UBUNTU_CODENAME/InRelease" 2>&1 | sed -n 's/.*using [A-Z]* key \([0-9A-F]*\).*/\1/p' | head -1 || true)"
if gpgv --keyring "$key_dgx" "$R/dists/$UBUNTU_CODENAME/InRelease" >/dev/null 2>&1; then inrel=Good; else inrel="**BAD/unverifiable**"; fi
idx="$(python3 -I - "$R/dists/$UBUNTU_CODENAME" <<'PY'
import hashlib, os, sys
base = sys.argv[1]
rel = open(os.path.join(base, "Release")).read().split("SHA256:")[1].split("\n")
ok = bad = 0
for line in rel[1:]:
    if not line.startswith(" "):
        break
    h, size, name = line.split()
    p = os.path.join(base, name)
    if os.path.exists(p) and hashlib.sha256(open(p, "rb").read()).hexdigest() == h:
        ok += 1
    else:
        bad += 1
print("%d ok, %d mismatched" % (ok, bad))
PY
)"
md "- **apt repo** \`dists/$UBUNTU_CODENAME\`: $(sed -n 's/^Origin: //p' "$R/dists/$UBUNTU_CODENAME/Release") / $(sed -n 's/^Label: //p' "$R/dists/$UBUNTU_CODENAME/Release"), $(sed -n 's/^Date: //p' "$R/dists/$UBUNTU_CODENAME/Release"). InRelease signed by key \`${inrel_key:-?}\`; gpgv against \`/etc/apt/trusted.gpg.d/dgx_debian_prod.gpg\` from the ubuntu-server layer: $inrel. Release SHA256 vs index files: $idx. Adding debs to \`pool/\` breaks this signature (cannot re-sign with NVIDIA's key): ship BrainSync packages in a separate repo on the ISO instead."
md "- **squashfs .gpg**: detached signatures by the Ubuntu CD Image key (2012, from the minimal layer). Results are in the layer table; NVIDIA rebuilt some layers without re-signing and the ISO still installs, so nothing in casper/subiquity checks them."
if [ "$sigcheck" = 1 ]; then
    log "md5sum -c over the tree"
    md5_bad="$(cd "$R" && md5sum -c --quiet md5sum.txt 2>/dev/null | wc -l | tr -d ' ')" || true
    md5_res="$(wc -l < "$R/md5sum.txt" | tr -d ' ') entries, ${md5_bad:-?} failing \`md5sum -c\`"
else
    md5_res="$(wc -l < "$R/md5sum.txt" | tr -d ' ') entries (not checked)"
fi
md "- **md5sum.txt**: $md5_res; excludes itself and \`boot/boot.cat\`; sorted by path in C locale. Consumed by casper-md5check (reported, not enforced) and the \"Check Disc\" grub entry. repack-iso.sh regenerates it byte-identically for an unchanged tree."
md '- **Secure Boot**: grub.cfg and tree files sit outside the shim/grub signature chain; only changing `*.efi` or the ESP would matter. Leave the ESP untouched.'
md "- **ESP integrity** (inferred from L4TLauncher strings): \`EFI/version\` and \`EFI/ISO_ID\` are cross-checked by the launcher; another reason never to rebuild the ESP."

mv "$out" "$report"
log "wrote $report ($(wc -l < "$report" | tr -d ' ') lines)"
if [ "$sigcheck" = 1 ]; then
    mkdir -p "$BRAINSYNCOS_ROOT/docs"
    cp "$report" "$BRAINSYNCOS_ROOT/docs/base-iso-inventory.md"
    log "updated tracked copy docs/base-iso-inventory.md"
fi
